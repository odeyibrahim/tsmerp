// Writes public/js/config.js from environment variables at deploy time.
// The anon key is a PUBLIC key by design (RLS is the security boundary), so
// shipping it to the browser is expected. The service-role key is never read here.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const url = process.env.VITE_SUPABASE_URL || process.env.SUPABASE_URL || '';
const anonKey = process.env.SUPABASE_ANON_KEY || process.env.VITE_SUPABASE_ANON_KEY || '';
const siteUrl = process.env.SITE_URL || process.env.URL || '';

if (!url || !anonKey) {
    console.warn('[build-config] VITE_SUPABASE_URL / SUPABASE_ANON_KEY not set — the app will show a setup screen.');
}
const body = `// GENERATED by scripts/build-config.mjs — do not edit or commit.\nexport default ${JSON.stringify({ supabaseUrl: url, anonKey, siteUrl }, null, 2)};\n`;
writeFileSync(join(root, 'public/js/config.js'), body);
console.log('[build-config] wrote public/js/config.js');
