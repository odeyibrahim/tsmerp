import { html, registerAction } from '../lib/ui.js';
import { state } from '../lib/state.js';
import { formatMoney, formatDate, toNumber, round2 } from '../lib/format.js';
import { formatPhone } from '../lib/nigeria.js';
import { LABELS } from '../lib/lifecycle.js';
import { loadTrip } from './trip.js';

export async function render({ id }) {
    const d = await loadTrip(id);
    if (d.error) return html`<div class="alert alert-error">${d.error}</div>`;
    const { trip: t, customer, vehicle, driver } = d;
    const c = state.company;
    const showFreight = state.role !== 'driver';
    return html`
        <div class="no-print waybill-bar">
            <a href="#/trips/${t.id}">← Back to trip</a>
            <div>
                ${showFreight ? html`<label class="inline"><input type="checkbox" data-change="waybill:toggle-freight"> Show freight on waybill</label>` : ''}
                <button class="btn btn-primary" data-action="waybill:print">Print / Save as PDF</button>
            </div>
        </div>
        <article class="waybill" id="waybill-sheet">
            <header>
                <div><h1>${c.name}</h1><p>${[c.address, c.state].filter(Boolean).join(', ')}${c.phone ? ' · ' + formatPhone(c.phone) : ''}</p>
                    ${c.rc_number ? html`<p>RC ${c.rc_number}</p>` : ''}</div>
                <div class="wb-no"><span>WAYBILL</span><strong>${t.waybill_no}</strong><small>Booking ${t.booking_no}</small></div>
            </header>
            <div class="wb-grid">
                <div><h3>Date</h3><p>${formatDate(t.pickup_date || t.created_at)}</p></div>
                <div><h3>Status</h3><p>${LABELS[t.status]}</p></div>
                <div><h3>Customer / consignor</h3><p>${customer ? customer.name : '—'}${customer && customer.phone ? html`<br>${formatPhone(customer.phone)}` : ''}</p></div>
                <div><h3>Consignee</h3><p>${t.consignee_name || '—'}${t.consignee_phone ? html`<br>${formatPhone(t.consignee_phone)}` : ''}</p></div>
                <div><h3>From</h3><p>${t.origin_state}${t.origin_address ? html`<br>${t.origin_address}` : ''}</p></div>
                <div><h3>To</h3><p>${t.destination_state}${t.destination_address ? html`<br>${t.destination_address}` : ''}</p></div>
                <div><h3>Vehicle</h3><p>${vehicle ? vehicle.plate_number : 'To be assigned'}${vehicle && vehicle.make ? html`<br>${[vehicle.make, vehicle.model].filter(Boolean).join(' ')}` : ''}</p></div>
                <div><h3>Driver</h3><p>${driver ? driver.full_name : 'To be assigned'}${driver && driver.phone ? html`<br>${formatPhone(driver.phone)}` : ''}</p></div>
            </div>
            <table class="wb-cargo"><thead><tr><th>Description of goods</th><th>Weight</th><th class="wb-freight" hidden>Freight</th></tr></thead>
                <tbody><tr><td>${t.cargo_description || '—'}</td><td>${t.cargo_weight_tonnes != null ? t.cargo_weight_tonnes + ' tonnes' : '—'}</td>
                <td class="wb-freight" hidden>${formatMoney(t.freight_amount, t.currency)}<br><small>Advance ${formatMoney(t.advance_paid, t.currency)} · Balance ${formatMoney(round2(toNumber(t.freight_amount) - toNumber(t.advance_paid)), t.currency)}</small></td></tr></tbody></table>
            ${t.notes ? html`<p class="wb-notes"><strong>Notes:</strong> ${t.notes}</p>` : ''}
            <div class="wb-sign">
                <div><span></span>Driver's signature</div>
                <div><span></span>Dispatcher</div>
                <div><span></span>Received by (name, signature, date)</div>
            </div>
            <p class="wb-foot">Goods received in good order and condition unless noted. Generated by ${c.name}.</p>
        </article>`;
}

registerAction('waybill:print', () => window.print());
registerAction('waybill:toggle-freight', (el) => {
    document.querySelectorAll('.wb-freight').forEach((n) => { n.hidden = !el.checked; });
});
